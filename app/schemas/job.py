from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, model_validator


# Define the data required to create a new job.
# Pydantic validates incoming data before it reaches the database.
class JobCreate(BaseModel):
    title: str = Field(min_length=1, max_length=255)
    company: str = Field(min_length=1, max_length=255)
    description: str | None = None
    salary_min: int | None = Field(default=None, ge=0)
    salary_max: int | None = Field(default=None, ge=0)
    url: str = Field(min_length=1, max_length=1000)

    # Validate that the minimum salary does not exceed the maximum salary.
    @model_validator(mode="after")
    def validate_salary_range(self):
        if (
            self.salary_min is not None
            and self.salary_max is not None
            and self.salary_min > self.salary_max
        ):
            raise ValueError(
                "Minimum salary cannot be greater than maximum salary"
            )

        return self


# Define the data returned to the API user.
# This schema also includes fields generated by the database.
class JobResponse(BaseModel):
    id: int
    title: str
    company: str
    description: str | None
    salary_min: int | None
    salary_max: int | None
    url: str
    created_at: datetime

    # Allow Pydantic to read data directly from SQLAlchemy objects.
    model_config = ConfigDict(from_attributes=True)
